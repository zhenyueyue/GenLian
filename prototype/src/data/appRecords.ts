export interface HistorySessionRecord {
  id: string;
  dateLabel: string;
  isoDate: string;
  weekday: string;
  planId: string;
  category: WorkoutCategory;
  title: string;
  outcome: Exclude<SessionOutcome, 'in_progress'>;
  durationSeconds: number;
  pausedSeconds: number;
  startedAt: string;
  endedAt: string;
  plannedSetsCount: number;
  loggedSets: LoggedSet[];
  skippedRecords: SkippedRecord[];
  primaryWeightLabel: string;
  isDemoData: boolean;
  note?: string;
}

